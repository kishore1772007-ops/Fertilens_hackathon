from typing import List, Optional, Any
from pydantic import BaseModel, Field

class Citation(BaseModel):
    document_id: str
    document_title: str
    page_number: int
    snippet: str
    similarity_score: Optional[float] = None

class RAGQuestionRequest(BaseModel):
    question: str = Field(..., min_length=3)
    session_id: Optional[str] = None
    stream: bool = False

class RAGAnswerResponse(BaseModel):
    question: str
    answer: str
    citations: List[Citation] = Field(default_factory=list)
    confidence: Optional[str] = "high"
    session_id: Optional[str] = None
    disclaimer: str = "This clinical synthesis is generated by FertiLens AI to assist fertility care teams and does not replace medical judgment."

class ConsultationBriefResponse(BaseModel):
    patient_id: str
    patient_name: str
    generated_at: str
    clinical_summary: str
    timeline_summary: str
    active_protocols: List[str]
    critical_alerts: List[str]
    citations: List[Citation]
